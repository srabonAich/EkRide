  static String translateTitle(String title, bool isBangla) {
    if (!isBangla) return title;
    if (title == 'Direct Solo Ride') return 'একক প্রাইভেট রাইড (Direct Solo)';
    if (title.startsWith('Triple Pool:')) {
      return title.replaceFirst('Triple Pool:', '৩ জনের ট্রিপল পুল:')
                  .replaceFirst('Passengers', 'জন')
                  .replaceAll('&', 'ও');
    }
    if (title.startsWith('Quad Pool:')) {
      return title.replaceFirst('Quad Pool:', '৪ জনের কোয়াড পুল:')
                  .replaceFirst('Passengers', 'জন')
                  .replaceAll('&', 'ও');
    }
    if (title.startsWith('Shared with ')) {
      return title.replaceFirst('Shared with ', 'শেয়ার্ড: ');
    }
    return title;
  }

